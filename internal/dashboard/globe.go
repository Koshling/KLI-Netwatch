// buildLandMask заливает контуры в равнопромежуточную сетку суши (scanline, even-odd).
func buildLandMask() {
	for _, poly := range landPolygons {
		fillPolygon(poly, true)
	}
	for _, poly := range waterPolygons {
		fillPolygon(poly, false)
	}
}

func fillPolygon(poly []geoPoint, value bool) {
	n := len(poly)
	if n < 3 {
		return
	}
	xs := make([]float64, 0, 16)
	for iy := 0; iy < maskH; iy++ {
		lat := 90 - (float64(iy)+0.5)*maskRes
		xs = xs[:0]
		for i := 0; i < n; i++ {
			a := poly[(i+n-1)%n]
			b := poly[i]
			if (a[1] <= lat) != (b[1] <= lat) {
				xs = append(xs, a[0]+(lat-a[1])*(b[0]-a[0])/(b[1]-a[1]))
			}
		}
		sort.Float64s(xs)
		for k := 0; k+1 < len(xs); k += 2 {
			from := int(math.Ceil((xs[k]+180)/maskRes - 0.5))
			to := int(math.Floor((xs[k+1]+180)/maskRes - 0.5))
			if from < 0 {
				from = 0
			}
			if to > maskW-1 {
				to = maskW - 1
			}
			for ix := from; ix <= to; ix++ {
				landMask[iy][ix] = value
			}
		}
	}
}

func isLand(lonDeg, latDeg float64) bool {
	lon := math.Mod(lonDeg+180, 360)
	if lon < 0 {
		lon += 360
	}
	ix := int(lon / maskRes)
	if ix >= maskW {
		ix = maskW - 1
	}
	iy := int((90 - latDeg) / maskRes)
	if iy < 0 {
		iy = 0
	}
	if iy >= maskH {
		iy = maskH - 1
	}
	return landMask[iy][ix]
}

// globeView описывает поворот сферы: долгота центра и наклон оси.
type globeView struct {
	lon0    float64 // долгота центра диска, градусы
	sinTilt float64
	cosTilt float64
}

// landAt обратно проецирует точку диска (nx, ny в [-1,1]) на сферу и
// проверяет, суша ли это. Точки вне диска — всегда океан.
func (v globeView) landAt(nx, ny float64) bool {
	r2 := nx*nx + ny*ny
	if r2 >= 1 {
		return false
	}
	z := math.Sqrt(1 - r2)
	y := -ny
	sinLat := y*v.cosTilt + z*v.sinTilt
	zz := z*v.cosTilt - y*v.sinTilt
	lat := math.Asin(math.Max(-1, math.Min(1, sinLat))) * 180 / math.Pi
	lon := v.lon0 + math.Atan2(nx, zz)*180/math.Pi
	return isLand(lon, lat)
}

const (
	cellOcean = iota
	cellLand
	cellRing
	cellNone
)

func renderGlobe(width, height int, angle float64, theme Theme) []string {
	if height <= 0 {
		return []string{}
	}
	result := make([]string, height)
	if width <= 0 {
		return result
	}
	if width < 7 || height < 3 {
		blank := strings.Repeat(" ", width)
		for i := range result {
			result[i] = blank
		}
		return result
	}

	landMaskOnce.Do(buildLandMask)

	cx := float64(width-1) / 2
	cy := float64(height-1) / 2
	rx := float64(width) * 0.46
	ry := float64(height) * 0.47

	// Пропорции старой версии, но с ограничением: видимое отношение ширины
	// к высоте (с учётом клетки 1:2) держим в диапазоне [globeMinAspect, globeMaxAspect].
	if aspect := rx / (2 * ry); aspect > globeMaxAspect {
		rx = 2 * ry * globeMaxAspect
	} else if aspect < globeMinAspect {
		ry = rx / (2 * globeMinAspect)
	}

	view := globeView{
		lon0:    -angle * 180 / math.Pi,
		sinTilt: math.Sin(globeTilt),
		cosTilt: math.Cos(globeTilt),
	}

	kind := make([][]uint8, height)
	depth := make([][]float64, height)
	for y := 0; y < height; y++ {
		kind[y] = make([]uint8, width)
		depth[y] = make([]float64, width)
		for x := 0; x < width; x++ {
			nx := (float64(x) - cx) / rx
			ny := (float64(y) - cy) / ry
			r := math.Hypot(nx, ny)

			// Толщина контура в долях радиуса ≈ полклетки вдоль направления к краю.
			half := 0.5 * (math.Abs(nx)/rx + math.Abs(ny)/ry) / math.Max(r, 1e-9)
			if r > 1+half {
				kind[y][x] = cellNone
				continue
			}
			if r >= 1-half {
				kind[y][x] = cellRing
				continue
			}

			depth[y][x] = math.Sqrt(math.Max(0, 1-r*r))

			// 4 подвыборки в клетке: береговая линия получается ровнее и плавнее при вращении.
			hits := 0
			for _, off := range [4][2]float64{{-0.25, -0.25}, {0.25, -0.25}, {-0.25, 0.25}, {0.25, 0.25}} {
				if view.landAt((float64(x)+off[0]-cx)/rx, (float64(y)+off[1]-cy)/ry) {
					hits++
				}
			}
			if hits >= 2 {
				kind[y][x] = cellLand
			} else {
				kind[y][x] = cellOcean
			}
		}
	}

	isOcean := func(x, y int) bool {
		return x >= 0 && x < width && y >= 0 && y < height && kind[y][x] == cellOcean
	}

	for y := 0; y < height; y++ {
		var line strings.Builder
		for x := 0; x < width; x++ {
			char := byte(' ')
			color := theme.Muted

			switch kind[y][x] {
			case cellRing:
				char = '.'
			case cellLand:
				z := depth[y][x]
				coast := isOcean(x-1, y) || isOcean(x+1, y) || isOcean(x, y-1) || isOcean(x, y+1)
				color = theme.Accent
				switch {
				case coast && z > 0.25:
					char = '#'
				case coast:
					char = '+'
				case z > 0.5:
					char = '+'
				case z > 0.25:
					char = ':'
				default:
					char = '.'
				}
			}

			if char == ' ' {
				line.WriteByte(' ')
			} else {
				line.WriteString(color)
				line.WriteByte(char)
				line.WriteString("\033[0m")
			}
		}
		result[y] = line.String()
	}

	return result
}
